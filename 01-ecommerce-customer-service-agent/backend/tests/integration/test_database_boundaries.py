import json
import os

import pytest
from alembic.autogenerate import compare_metadata
from alembic.migration import MigrationContext
from sqlalchemy import create_engine, inspect, text
from sqlalchemy.exc import DBAPIError

from cs_agent.config import PROJECT_ROOT, Settings
from cs_agent.db.models import Base
from cs_agent.db.session import Database, verify_target


def test_runtime_role_has_no_ddl_identity_write_or_audit_rewrite():
    db = Database(
        Settings(
            database_url=os.environ["CS_TEST_DATABASE_URL"], expected_database="cs_agent_b0_test"
        )
    )
    for statement in [
        "CREATE TABLE forbidden_table(id integer)",
        "UPDATE subject SET auth_version=9",
        "DELETE FROM audit_event",
        "UPDATE audit_event SET action='bad'",
        "UPDATE cs_project_guard SET instance_id='bad'",
    ]:
        with pytest.raises(DBAPIError):
            with db.engine.begin() as conn:
                conn.execute(text(statement))
    db.close()


def test_migration_wrong_role_or_database_is_rejected_before_ddl():
    engine = create_engine(os.environ["CS_TEST_DATABASE_URL"], hide_parameters=True)
    with pytest.raises(RuntimeError, match="isolation mismatch"):
        verify_target(engine, Settings(expected_database="cs_agent_b0_test"), migration=True)
    with pytest.raises(RuntimeError, match="isolation mismatch"):
        verify_target(engine, Settings(expected_database="old_project"))
    engine.dispose()


def test_next_autogenerated_migration_cannot_remove_provenance_or_scope_constraints():
    engine = create_engine(os.environ["CS_TEST_MIGRATION_URL"], hide_parameters=True)
    with engine.connect() as conn:
        context = MigrationContext.configure(
            conn,
            opts={
                "include_object": lambda obj, name, type_, reflected, compare_to: (
                    name != "cs_project_guard"
                )
            },
        )
        assert compare_metadata(context, Base.metadata) == []
    engine.dispose()


def test_real_schema_contains_every_mapped_and_required_dictionary_field():
    engine = create_engine(os.environ["CS_TEST_MIGRATION_URL"], hide_parameters=True)
    inspector = inspect(engine)
    for table in Base.metadata.tables.values():
        actual = {column["name"]: column for column in inspector.get_columns(table.name)}
        assert set(table.columns.keys()) == set(actual), table.name
        for column in table.columns:
            assert column.nullable == actual[column.name]["nullable"], (table.name, column.name)
    with engine.connect() as conn:
        assert conn.execute(text("SHOW server_encoding")).scalar_one() == "UTF8"
        assert (
            conn.execute(
                text(
                    "SELECT current_user, (SELECT rolsuper OR rolbypassrls FROM pg_roles WHERE rolname=current_user)"
                )
            ).one()[1]
            is False
        )
    manifest = json.loads(
        (PROJECT_ROOT / "data/synthetic/manifest.json").read_text(encoding="utf-8")
    )
    assert manifest["opening_balance_minor"] == "0"
    engine.dispose()
